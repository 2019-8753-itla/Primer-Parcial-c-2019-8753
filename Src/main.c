/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */
  

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USART2_UART_Init();
  MX_TIM2_Init();
  MX_TIM6_Init();
  /* USER CODE BEGIN 2 */

  HAL_TIM_Base_Start_IT(&htim6);
  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_1);

  buttonRawState =
      HAL_GPIO_ReadPin(USER_BTN_GPIO_Port, USER_BTN_Pin);

  buttonStableState = buttonRawState;

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

	  uint32_t now = g_ms;

	  /* Se detectó un flanco mediante EXTI */
	  if (buttonEdgePending)
	  {
	      buttonEdgePending = 0;

	      buttonRawState =
	          HAL_GPIO_ReadPin(USER_BTN_GPIO_Port, USER_BTN_Pin);

	      debounceStart = now;
	      debounceActive = 1;
	  }

	  /* Validación no bloqueante de 30 ms */
	  if (debounceActive)
	  {
	      uint8_t currentState =
	          HAL_GPIO_ReadPin(USER_BTN_GPIO_Port, USER_BTN_Pin);

	      /* Si vuelve a cambiar, reiniciamos los 30 ms */
	      if (currentState != buttonRawState)
	      {
	          buttonRawState = currentState;
	          debounceStart = now;
	      }

	      /* Debe permanecer estable durante 30 ms */
	      if ((uint32_t)(now - debounceStart) >= 30U)
	      {
	          debounceActive = 0;

	          if (buttonStableState != buttonRawState)
	          {
	              buttonStableState = buttonRawState;

	              /* B1 es activo en bajo */
	              if (buttonStableState == GPIO_PIN_RESET)
	              {
	                  /* Pulsación validada */
	                  buttonPressed = 1;
	                  pressStart = now;
	                  longPressReported = 0;
	              }
	              else
	              {
	                  /* Liberación validada */
	                  if (buttonPressed)
	                  {
	                      if (!longPressReported)
	                      {
	                          uint32_t pressDuration =
	                              (uint32_t)(now - pressStart);

	                          if (pressDuration >= 30U &&
	                              pressDuration < 1500U)
	                          {
	                              shortPressCount++;
	                          }
	                      }

	                      buttonPressed = 0;
	                  }
	              }
	          }
	      }
	  }
	  /* Detección de pulsación larga */
	  if (buttonPressed && !longPressReported)
	  {
	      if ((uint32_t)(now - pressStart) >= 1500U)
	      {
	          longPressReported = 1;
	          longPressCount++;
	      }
	  }
  }
  /* USER CODE END 3 */
}

